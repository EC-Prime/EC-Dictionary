    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        // TODO add your handling code here:
        String oldTerm = termField.getText();

        if (JavaApplication19.terms.containsKey(oldTerm)) {
            String newDef = defArea.getText();
            JavaApplication19.terms.put(oldTerm, newDef);
            statusLabel.setText(oldTerm+" Updated!");
            JavaApplication19.saveToFile();
            refreshList();
            termField.setText("");
            defArea.setText("");
        } else {
            statusLabel.setText(oldTerm+" could not be updated as it does not exist!");
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        // TODO add your handling code here:
        String searchTerm = termField.getText();

        if (JavaApplication19.terms.containsKey(searchTerm)) {
             String def = JavaApplication19.terms.get(searchTerm);
             statusLabel.setText(searchTerm + ": " + def);
        } else {
           statusLabel.setText(searchTerm+ " Not found in dictionary!");
        }
    }//GEN-LAST:event_searchBtnActionPerformed

