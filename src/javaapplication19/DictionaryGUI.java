    private void refreshList(){
        listModel.clear();
        for (String term : JavaApplication19.terms.keySet()){
        listModel.addElement(term);
    }
}
    
    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        // TODO add your handling code here:
        String term = termField.getText();
        String def = defArea.getText();
        
        if (JavaApplication19.terms.containsKey(term)) {
            statusLabel.setText("Term is already added to dictionary");
        } else {
            JavaApplication19.terms.put(term, def);
            statusLabel.setText("New term added!");
            JavaApplication19.saveToFile();
            refreshList();
            termField.setText("");
            defArea.setText("");
        }
    }//GEN-LAST:event_addBtnActionPerformed

    private void removeBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeBtnActionPerformed
        // TODO add your handling code here:
        String searchTerm = termField.getText();

        if (JavaApplication19.terms.containsKey(searchTerm)) {
            JavaApplication19.terms.remove(searchTerm);

            statusLabel.setText(searchTerm+" successfully removed!");
            JavaApplication19.saveToFile();
            refreshList();
        } else {
            statusLabel.setText(searchTerm + " is not in the dictionary!");
        }
    }//GEN-LAST:event_removeBtnActionPerformed

